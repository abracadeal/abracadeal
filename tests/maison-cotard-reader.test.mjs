import assert from 'node:assert/strict';
import fs from 'node:fs';
import {maisonCotardCatalogue, parseMaisonCotard} from '../supabase/functions/pro-stock-sync/maison-cotard-reader.ts';

const fixture = name => fs.readFileSync(new URL('./fixtures/maison-cotard/' + name + '.html', import.meta.url), 'utf8');
const scope = new URL('https://www.maisoncotard.com/a-vendre');
const catalogue = fixture('catalogue');
const otherLinks = '<a href="/vendu-appartement">Vendu</a><a class="bien" href="https://example.org/a-vendre/maison-1">Autre site</a>';
const {details, lists} = maisonCotardCatalogue(catalogue + otherLinks, scope);
assert.equal(details.length, 7);
assert.equal(lists.length, 0);
assert.deepEqual(maisonCotardCatalogue(catalogue + '<a rel="next" href="?page=2">Suite</a>', scope).lists, [scope.href + '?page=2']);
const nation = parseMaisonCotard(fixture('nation'), details[0]);
assert.equal(nation.prix, 1350000);
assert.equal(nation.surface, 100.89);
assert.equal(nation.chambres, 2);
assert.equal(nation.nombre_etages, 9);
assert.equal(nation.mandat, 'MCI.67');
assert.equal(nation.charges_annuelles, 6300);
assert.equal(nation.taxe_fonciere, 2200);
assert.deepEqual([nation.dpe, nation.ges, nation.cout_energie_min], ['D', 'D', 1280]);
assert.deepEqual([nation.contact_nom, nation.contact_telephone], ['Yann Cotard', '0667330614']);
assert.match(nation.description, /emplacement de parking en sous-sol/);
assert.match(nation.surfacespieces, /Séjour : 40,08 m²/);
assert.equal(nation.photos.split('|').length, 17);
const lyonUrl = details.find(url => url.endsWith('rue-de-lyon'));
const lyon = parseMaisonCotard(fixture('lyon'), lyonUrl);
assert.equal(lyon.photos.split('|').length, 5);
assert.doesNotMatch(lyon.equipements, /ascenseur/i);
assert.throws(() => parseMaisonCotard(fixture('lyon'), details[0]), /Identité/);
assert.throws(() => parseMaisonCotard(fixture('lyon').replace('Voir les 10 photos', 'Voir les 11 photos'), lyonUrl), /Galerie/);
assert.throws(() => parseMaisonCotard(fixture('nation').replace('<p class="bigprice">1', '<p class="bigprice">2'), details[0]), /prix contradictoire/);
console.log('Maison Cotard: catalogue scoped, published pagination, facts, source contacts, full gallery without virtual or stock images');
